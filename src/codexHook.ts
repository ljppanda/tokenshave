/**
 * Generates the Codex CLI adapter: a PostToolUse command hook that replaces
 * the model-visible result of completed shell commands with its shaved form.
 *
 * Verified against Codex CLI 0.166.0 (see VERIFY.md; engine-level facts read
 * from the openai/codex sources):
 *  - the "hooks" feature is stable in 0.166.0 (checked via `codex features
 *    list`, no flag needed)
 *  - shell commands hit hooks under the canonical tool name "Bash" (matches
 *    matcher "Bash"), for both exec_command and one-shot shells
 *  - PostToolUse fires for every COMPLETED command; stdin JSON carries
 *    tool_response as a plain STRING (the model-facing, already-truncated
 *    output) and tool_input as { command: "<original command>" }
 *  - a sync command hook may replace the model-visible result by printing
 *    { "continue": false, "reason": "<text>", "stopReason": "<short>" }:
 *    Codex swaps the tool result for `reason` (a normal success-shaped
 *    result, not an error). decision:"block" exists but turns the result
 *    into an error — wrong shape for shaving.
 *  - empty stdout + exit 0 = pass-through (the engine contract is fail-open:
 *    any error prints nothing and Codex keeps the original result; a strict
 *    schema means even an invalid body just marks the hook failed and the
 *    original output survives)
 *  - plugin-bundled hooks live in hooks/hooks.json at the plugin root; the
 *    command runs through the platform shell (cmd /C on Windows), so
 *    shave.js guarantees its own exit code — no shell separators
 *  - plugins are discovered through marketplace manifests at
 *    .agents/plugins/marketplace.json (repo root) pointing at a payload
 *    folder that carries .codex-plugin/plugin.json
 */

import { loadEngineBundle } from "./claudeBundle.js";

export const CODEX_HOOK_MARKER = "tokenshave — generated by `npx tokenshave install` (Codex CLI hook)";

export interface CodexHookFiles {
  hooksJson: string;
  shaveJs: string;
  pluginJson?: string;
  readme: string;
}

/**
 * The hook fits two layouts:
 *  - the repo's marketplace payload (`codex-mod/`): command uses the
 *    plugin-specific PLUGIN_ROOT directory
 *  - a project-local install: command points at the generated script by
 *    absolute path (Codex runs hooks with the session cwd, which is not
 *    guaranteed to be the project root)
 */
export async function generateCodexHookFiles(
  generatedAt: string,
  version: string,
  command: string,
  engineBundle?: string,
): Promise<CodexHookFiles> {
  const engine = engineBundle ?? (await loadEngineBundle());

  const hooksJson = `${JSON.stringify(
    {
      description: `tokenshave hooks module — ${CODEX_HOOK_MARKER}`,
      hooks: {
        PostToolUse: [
          {
            matcher: "Bash",
            hooks: [
              {
                type: "command",
                command,
                timeout: 15,
                statusMessage: "Shaving shell output with tokenshave",
              },
            ],
          },
        ],
      },
    },
    null,
    2,
  )}\n`;

  const shaveJs = `// ${CODEX_HOOK_MARKER} on ${generatedAt} (tokenshave ${version})
// Uninstall with \`npx tokenshave uninstall\`, or delete this file/directory.
//
// Codex CLI PostToolUse hook for the Bash tool: replaces the model-visible
// result of a completed shell command with its shaved form. The engine is
// inlined below (pure computation: no imports, no network, no data
// collection) and you can read every line it runs.
//
// Contract, per codex-rs 0.166.0 (openai/codex sources, see VERIFY.md):
//  - stdin: one JSON object { tool_name: "Bash", tool_input: { command },
//    tool_response: <model-facing output string>, ... }
//  - stdout JSON { continue: false, reason: <text>, stopReason: <short> }
//    replaces the tool result the model sees; empty stdout + exit 0 keeps
//    the original result untouched (fail open — every path below prints
//    nothing on any error or pass-through case, and this file always
//    exits 0, which the command runner runs through the platform shell)

${engine}

const TSH_MIN_CHARS = 50;

function tshHandle(input) {
  try {
    const e = JSON.parse(input);
    if (!e || e.hook_event_name !== "PostToolUse") return null
    if (e.tool_name !== "Bash") return null
    const response = e.tool_response;
    if (typeof response !== "string" || response.length < TSH_MIN_CHARS) return null
    const args = e.tool_input;
    const cmd =
      args && typeof args.command === "string" && args.command.trim() !== ""
        ? args.command
        : "bash";
    const result = shave(cmd, response);
    if (result.output === response) return null
    return JSON.stringify({
      continue: false,
      stopReason:
        "tokenshave: trimmed " +
        (result.rawLines - result.keptLines) +
        " of " +
        result.rawLines +
        " lines (head, tail and errors kept)",
      reason: result.output,
    });
  } catch {
    return null
  }
}

let tshChunks = [];
process.stdin.on("data", (chunk) => tshChunks.push(chunk));
process.stdin.on("end", () => {
  let output = null;
  try {
    output = tshHandle(Buffer.concat(tshChunks).toString("utf8"));
  } catch {
    output = null;
  }
  if (output) process.stdout.write(output);
  process.exit(0);
});
`;

  const pluginJson = `${JSON.stringify(
    {
      name: "tokenshave",
      version,
      description:
        "Shaves noisy shell-command output (npm/test/git/build logs) before it enters Codex's context",
      author: { name: "ljppanda", url: "https://github.com/ljppanda" },
      homepage: "https://github.com/ljppanda/tokenshave",
      repository: "https://github.com/ljppanda/tokenshave",
      license: "MIT",
      keywords: ["tokens", "context", "cost", "logs"],
    },
    null,
    2,
  )}\n`;

  const readme = `# tokenshave (Codex CLI hook)

${CODEX_HOOK_MARKER} on ${generatedAt} (tokenshave ${version}).

This plugin shaves the noisy output of Codex shell commands — npm/test/git/
build logs — before it enters the session context. It keeps the head and tail
of each output and every error-bearing line, and replaces the removed middle
with explicit marker lines. No network calls, no data collection, no
dependencies: the engine is inlined in \`hooks/shave.js\`.

After installing, open Codex and run \`/hooks\` to review and trust the hook:
Codex skips untrusted hooks (shown and trusted once, then hashed).
`;

  return { hooksJson, shaveJs, pluginJson, readme };
}
