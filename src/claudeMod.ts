/**
 * Generates the Claude Code adapter: a self-contained mod (plugin with an
 * in-process hooks module) that shaves Bash tool output.
 *
 * Verified facts this generator relies on (Claude Code 2.1.314, see VERIFY.md):
 *  - mod layout: .claude-plugin/plugin.json + hooks/hooks.json (modules:
 *    ["./register.js"]) + register.js exporting register(on)
 *  - `tool.call` middleware: await next(e) resolves to the tool result;
 *    returning a copy rewrites what Claude reads
 *  - Bash event: e.tool === "Bash", e.command is the shell command;
 *    Bash result: { stdout: string; stderr: string; interrupted: boolean; ... }
 *  - a hooks module may import ONLY files inside the plugin directory by
 *    relative path (and the claude-code package) — no node: imports; so the
 *    mod is fully self-contained with the engine inlined
 *  - loading without a marketplace requires --plugin-dir; loading in place
 *    works from a marketplace added from a local directory
 *    (project scope: `claude plugin marketplace add <dir> --scope project`),
 *    and such plugins keep loading the current files every session
 */

import { loadEngineBundle } from "./claudeBundle.js";
import { join } from "node:path";

export const CLAUDE_MOD_MARKER = "tokenshave — generated by `npx tokenshave install` (Claude Code mod)";
export const CLAUDE_MARKETPLACE_MARKER = "generated by tokenshave install";

export interface ClaudeModTargets {
  marketplaceJson: string;
  pluginJson: string;
  hooksJson: string;
  registerJs: string;
  readme: string;
}

export function claudeModTargets(dir: string): ClaudeModTargets {
  const modRoot = join(dir, ".tokenshave", "claude");
  return {
    marketplaceJson: join(modRoot, "marketplace.json"),
    pluginJson: join(modRoot, "mod", ".claude-plugin", "plugin.json"),
    hooksJson: join(modRoot, "mod", "hooks", "hooks.json"),
    registerJs: join(modRoot, "mod", "hooks", "register.js"),
    readme: join(modRoot, "mod", "README.md"),
  };
}

const MOD_DESCRIPTION =
  "Shaves noisy shell-tool output (npm/test/git/build logs) in Claude Code sessions: keeps head, tail and error lines, replaces the rest with marker lines";

export function generateClaudeModFiles(
  generatedAt: string,
  engineBundle: string,
  version: string,
): Array<{ target: keyof ClaudeModTargets; content: string }> {
  const hooksJson = `${JSON.stringify(
    { description: `tokenshave hooks module — ${CLAUDE_MARKETPLACE_MARKER}`, modules: ["./register.js"] },
    null,
    2,
  )}\n`;

  const pluginJson = `${JSON.stringify(
    {
      name: "tokenshave",
      version,
      description: `${MOD_DESCRIPTION} (${CLAUDE_MARKETPLACE_MARKER})`,
      author: { name: "ljppanda", url: "https://github.com/ljppanda" },
      homepage: "https://github.com/ljppanda/tokenshave",
      repository: "https://github.com/ljppanda/tokenshave",
      license: "MIT",
      keywords: ["tokens", "context", "cost", "logs"],
    },
    null,
    2,
  )}\n`;

  const marketplaceJson = `${JSON.stringify(
    {
      name: "tokenshave-local",
      owner: { name: "tokenshave" },
      description: `${CLAUDE_MARKETPLACE_MARKER} — project-local marketplace for the tokenshave Claude Code mod`,
      plugins: [{ name: "tokenshave", source: "./mod" }],
    },
    null,
    2,
  )}\n`;

  const readme = `# tokenshave (Claude Code mod)

${CLAUDE_MOD_MARKER} on ${generatedAt}. Uninstall with \`npx tokenshave uninstall\`, or delete this directory.

This mod shaves the noisy output of the Bash tool — npm/test/git/build logs —
before it enters the session context. It keeps the head and tail of the output,
every error-bearing line (not ok, failed, exit code, ...), and replaces the
removed middle with explicit marker lines, so the agent always knows what was
trimmed and where. stdout and stderr are shaved separately, keyed on the shell
command, so each rule matches the log format it was written for.

No network calls, no data collection, no dependencies: the whole engine is
inlined in \`hooks/register.js\`, and you can read every line it runs.

This local mod loads in place from \`.tokenshave/claude/marketplace.json\`.
The same shave engine ships from the public marketplace too:

\`\`\`
/plugin install tokenshave --marketplace ljppanda/tokenshave
\`\`\`
`;

  const registerJs = `// ${CLAUDE_MOD_MARKER} on ${generatedAt}
// Uninstall with \`npx tokenshave uninstall\`, or delete this directory.
//
// Shaves Bash tool output before it enters the context. The engine is
// inlined below (Claude Code hooks modules may only import their own plugin
// files — verified against the mod loader of 2.1.314) and is pure
// computation: no imports, no network, no data collection.
//
// Behaviour contract, identical to the OpenCode plugin:
//  - keyed on the shell command (e.command), not the tool name
//  - head, tail and error lines kept; removed text replaced with markers
//  - outputs under 50 characters pass through untouched
//  - image outputs and non-standard results pass through untouched
//  - any failure passes the original result through (fail open), and the
//    hook never blocks a command

${engineBundle}

const TSH_MIN_CHARS = 50;

const TSH_HOOK = async ($, e, next) => {
  const result = await next(e)
  try {
    if (!result || typeof result !== "object") return result
    // two shapes reach a hook, both observed with "claude plugin test":
    //  - the tool ran: the Bash result record directly ({ stdout, stderr, ... })
    //  - another hook answered in its place: { result: <that hook's answer> }
    const raw = result.result && typeof result.result === "object" ? result.result : result
    const envelope = raw !== result
    if (typeof raw.stdout !== "string" || raw.isImage) return result
    const cmd = typeof e.command === "string" && e.command.trim() !== "" ? e.command : "bash"
    const outTooBig = raw.stdout.length >= TSH_MIN_CHARS
    const errTooBig = typeof raw.stderr === "string" && raw.stderr.length >= TSH_MIN_CHARS
    if (!outTooBig && !errTooBig) return result

    let stdout = raw.stdout
    if (outTooBig) stdout = shave(cmd, raw.stdout).output
    // stderr gets its own pass: stderr is almost all error lines, which the
    // engine always keeps, so this pass only removes its filler bulk
    let stderr = typeof raw.stderr === "string" ? raw.stderr : undefined
    if (errTooBig) stderr = shave(cmd, raw.stderr).output

    if (stdout === raw.stdout && stderr === raw.stderr) return result
    const shaved = { ...raw, stdout }
    if (errTooBig) shaved.stderr = stderr
    return envelope ? { ...result, result: shaved } : shaved
  } catch {
    // fail open: the agent sees exactly what the tool returned
    return result
  }
}

const TSH_CATCH = async ($, e, next) => {
  // whatever went wrong, keep the event flowing: when the hook had not
  // reached next(e) yet this runs the command normally; when it had, this
  // returns the result the command already produced
  return next(e)
}

export function register(on) {
  on("tool.call", { tool: "Bash" }, TSH_HOOK).catch(TSH_CATCH)
}
`;

  return [
    { target: "hooksJson", content: hooksJson },
    { target: "pluginJson", content: pluginJson },
    { target: "registerJs", content: registerJs },
    { target: "readme", content: readme },
    { target: "marketplaceJson", content: marketplaceJson },
  ];
}
